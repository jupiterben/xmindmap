import { test, expect } from '@playwright/test'
import type { Page } from '@playwright/test'

async function selectRoot(page: Page) {
  await page.getByTestId('mind-map-canvas').locator('text').filter({ hasText: /^产品设计$/ }).click()
}
async function settings(page: Page) {
  await page.getByRole('button', { name: 'AI 连接设置', exact: true }).click()
  await page.getByText('快捷键设置', { exact: false }).click()
}

test('AI shortcut focuses persistent input, persists customization and supports disable/reset', async ({ page }) => {
  let requests = 0
  await page.route('**/chat/completions', async (route) => { requests++; await route.abort() })
  await page.goto('/')
  await expect(page.getByText('正在打开导图')).toBeHidden()
  const input = page.getByLabel('AI 对话消息')
  await selectRoot(page)
  await page.keyboard.press('Control+Alt+a')
  await expect(input).toBeFocused()
  await expect(page.locator('dialog[open]')).toHaveCount(0)
  await settings(page)
  await page.getByLabel('AI 快捷键按键').selectOption('KeyB')
  await page.getByRole('button', { name: '保存快捷键', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('快捷键已保存')
  await page.keyboard.press('Escape')
  await selectRoot(page)
  await page.keyboard.press('Control+Alt+a')
  await expect(input).not.toBeFocused()
  await page.keyboard.press('Control+Alt+b')
  await expect(input).toBeFocused()
  await page.reload()
  await expect(page.getByText('正在打开导图')).toBeHidden()
  await selectRoot(page)
  await page.keyboard.press('Control+Alt+b')
  await expect(input).toBeFocused()
  await settings(page)
  await expect(page.getByLabel('AI 快捷键按键')).toHaveValue('KeyB')
  await page.getByLabel('启用 AI 扩展快捷键').uncheck()
  await page.getByRole('button', { name: '保存快捷键', exact: true }).click()
  await expect.poll(() => page.evaluate(() => localStorage.getItem('xmindmap.ai.shortcut.v1'))).toBe('')
  await page.keyboard.press('Escape')
  await selectRoot(page)
  await page.keyboard.press('Control+Alt+b')
  await expect(input).not.toBeFocused()
  await settings(page)
  await page.getByRole('button', { name: '恢复默认 AI 快捷键' }).click()
  await expect.poll(() => page.evaluate(() => localStorage.getItem('xmindmap.ai.shortcut.v1'))).toBe('Mod+Alt+KeyA')
  await page.keyboard.press('Escape')
  await selectRoot(page)
  await page.keyboard.press('Control+Alt+a')
  await expect(input).toBeFocused()
  expect(requests).toBe(0)
})

test('AI shortcut ignores text editing, settings and multi-selection', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByText('正在打开导图')).toBeHidden()
  const input = page.getByLabel('AI 对话消息')
  await page.getByLabel('文档名称').focus()
  await page.keyboard.press('Control+Alt+a')
  await expect(input).not.toBeFocused()
  await selectRoot(page)
  await page.getByTestId('mind-map-canvas').locator('text').filter({ hasText: /^产品设计$/ }).dblclick()
  await expect(page.locator('.smm-node-edit-wrap')).toBeVisible()
  await page.keyboard.press('Control+Alt+a')
  await expect(input).not.toBeFocused()
  await page.keyboard.press('Enter')
  await page.getByRole('button', { name: 'AI 连接设置', exact: true }).click()
  await page.getByLabel('服务商 API Key').fill('保留这段输入')
  await page.keyboard.press('Control+Alt+a')
  await expect(page.getByLabel('服务商 API Key')).toHaveValue('保留这段输入')
  await page.keyboard.press('Escape')
  const canvas = page.getByTestId('mind-map-canvas')
  await canvas.locator('text').filter({ hasText: /^用户访谈$/ }).click()
  await canvas.locator('text').filter({ hasText: /^场景与痛点$/ }).click({ modifiers: ['Control'] })
  await expect(page.getByRole('button', { name: 'AI 对话', exact: true })).toBeEnabled()
  await expect(input).toBeDisabled()
  await page.keyboard.press('Control+Alt+a')
  await expect(input).not.toBeFocused()
})

test('shortcut settings remain independent of model configuration on mobile', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await expect(page.getByText('正在打开导图')).toBeHidden()
  await settings(page)
  await page.getByLabel('AI 快捷键组合').selectOption({ label: 'Ctrl + Alt + Shift' })
  await page.getByLabel('AI 快捷键按键').selectOption('Digit3')
  await page.getByRole('button', { name: '保存快捷键', exact: true }).click()
  await expect.poll(() => page.evaluate(() => localStorage.getItem('xmindmap.ai.shortcut.v1'))).toBe('Mod+Alt+Shift+Digit3')
  const dialog = page.getByRole('dialog', { name: 'AI 设置', exact: true })
  expect(await dialog.evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true)
})
